export function getArticle(slug: string): LearnArticle | undefined {
  return LEARN_ARTICLES.find((a) => a.slug === slug);
}

export function getArticleNeighbors(slug: string): {
  prev: LearnArticle | null;
  next: LearnArticle | null;
} {
  const idx = LEARN_ARTICLES.findIndex((a) => a.slug === slug);
  return {
    prev: idx > 0 ? LEARN_ARTICLES[idx - 1] : null,
    next: idx >= 0 && idx < LEARN_ARTICLES.length - 1 ? LEARN_ARTICLES[idx + 1] : null,
  };
}
